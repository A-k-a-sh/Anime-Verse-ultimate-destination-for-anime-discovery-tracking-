const mongoose = require('mongoose');

const pulseSchema = new mongoose.Schema({
  title: {
    type: String,
    required: [true, 'Pulse title is required'],
    trim: true,
    maxlength: [150, 'Title cannot exceed 150 characters']
  },
  slug: {
    type: String,
    required: [true, 'Pulse slug is required'],
    unique: true,
    lowercase: true,
    trim: true,
    index: true // e.g. "gojo-domain-expansion-breakdown-9x7b"
  },
  excerpt: {
    type: String,
    trim: true,
    maxlength: [300, 'Excerpt cannot exceed 300 characters']
  },
  content: {
    type: String, // Sanitized HTML content generated by TipTap
    required: [true, 'Pulse content cannot be empty']
  },
  coverImage: {
    url: { type: String, default: null },
    publicId: { type: String, default: null }
  },
  author: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: [true, 'Author is required'],
    index: true
  },
  tags: [{
    type: String,
    trim: true,
    lowercase: true
  }], // e.g. ['theory', 'review', 'analysis', 'shonen']

  // Multi-media catalog linkage
  relatedMedia: [{
    malId: { type: Number, required: true },
    type: { type: String, enum: ['anime', 'manga'], required: true },
    title: { type: String, required: true },
    imageUrl: { type: String }
  }],

  hasSpoilers: {
    type: Boolean,
    default: false
  },
  commentsEnabled: {
    type: Boolean,
    default: true
  },
  views: {
    type: Number,
    default: 0
  },
  readingTimeMinutes: {
    type: Number,
    default: 3
  },

  // Reddit-style Voting & Pulse Score
  upvotes: [{ type: mongoose.Schema.Types.ObjectId, ref: 'User' }],
  downvotes: [{ type: mongoose.Schema.Types.ObjectId, ref: 'User' }],
  pulseScore: {
    type: Number,
    default: 0,
    index: true // Indexed for Top/Trending queries
  },

  status: {
    type: String,
    enum: ['draft', 'published'],
    default: 'published',
    index: true
  }
}, { timestamps: true });

// Compound indexes for fast feeds & searches
pulseSchema.index({ status: 1, createdAt: -1 });
pulseSchema.index({ status: 1, pulseScore: -1 });
pulseSchema.index({ 'relatedMedia.malId': 1, status: 1 });
pulseSchema.index({ title: 'text', excerpt: 'text', tags: 'text' });

module.exports = mongoose.model('Pulse', pulseSchema);
